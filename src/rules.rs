// Directed structural rules ported from rules.egg. Analysis handles arithmetic and bounds.
// Select is the zero-or-one-element list at an index, keeping projection relational
// without distributing conditionals through every consumer. Mirror patterns below
// handle === explicitly; no general commutation or association rules are installed.
// Short-list structure is exposed only at its consumers. Rel and At(Sublist) stay
// semantic primitives until concrete endpoints justify opening their definitions.
fn make_rules() -> Vec<Rule> {
    let mut rules = vec![
        rw!("reduce-cons"; "(MCall1 reduce (Cons ?h ?t) ?f)" => "(Foldl ?f ?h ?t)"),
        rw!("F4-identity"; "(Foldl (Lam ?acc (Lam ?v (Var ?v))) ?z ?xs)" => "(Maybe ?z (IndexQ ?xs (Sub (Len ?xs) (Num 1))))" if different("?acc","?v")),
        rw!("select-first"; "(IndexQ (Select ?xs ?j) (Num 0))" => "(IndexQ ?xs ?j)"),
        rw!("select-first-total"; "(At (Select ?xs ?j) (Num 0))" => "(At ?xs ?j)"),
        rw!("append-default"; "(IndexQ (Append ?xs (Cons ?z ?tail)) (Num 0))" => "(Maybe ?z (IndexQ ?xs (Num 0)))"),
        rw!("prefix-last"; "(IndexQ (Cons ?z ?xs) (Len ?xs))" => "(Maybe ?z (IndexQ ?xs (Sub (Len ?xs) (Num 1))))"),
        rw!("sublist-tail"; "(Sublist (Cons ?h ?t) (Num 1) (Len (Cons ?h ?t)))" => "?t"),
        rw!("short-last"; "(IndexQ ?xs ?k)" => ShortRead),
        rw!("prop"; "(Prop ?xs length)" => "(Len ?xs)"),
        rw!("elem"; "(Elem ?xs ?k)" => "(IndexQ ?xs ?k)"),
        rw!("arr-cons"; "(ArrCons ?h ?t)" => "(Cons ?h ?t)"),
        rw!("arr-spread"; "(ArrSpread ?xs ?t)" => "(Append ?xs ?t)"),
        rw!("coalesce"; "(Coalesce ?a ?b)" => "(Maybe ?b ?a)"),
        rw!("default"; "(Default ?m ?d)" => "(Maybe ?d ?m)"),
        rw!("m-call2"; "(MCall2 slice ?xs ?a ?b)" => "(Sublist ?xs (Rel ?a (Len ?xs)) (Rel ?b (Len ?xs)))"),
        rw!("m-call1"; "(MCall1 slice ?xs ?a)" => "(Sublist ?xs (Rel ?a (Len ?xs)) (Len ?xs))"),
        rw!("m-call0"; "(MCall0 slice ?xs)" => "?xs"),
        rw!("rel"; "(Rel ?k ?n)" => "(If (Lt ?k (Num 0)) (Max (Add ?n ?k) (Num 0)) (Min ?k ?n))" if known("?k")),
        rw!("m-call1-2"; "(MCall1 at ?xs ?k)" => "(IndexQ ?xs (If (Lt ?k (Num 0)) (Add (Len ?xs) ?k) ?k))"),
        rw!("m-call2-2"; "(MCall2 reduce ?xs ?f ?z)" => "(Foldl ?f ?z ?xs)"),
        rw!("m-call1-3"; "(MCall1 reduce ?xs ?f)" => "(If (Lt (Num 0) (Len ?xs)) (Foldl ?f (At ?xs (Num 0)) (Sublist ?xs (Num 1) (Len ?xs))) (Throw))" if not_cons("?xs")),
        rw!("m-call1-4"; "(MCall1 map ?xs ?f)" => "(Map ?f ?xs)"),
        rw!("m-call1-5"; "(MCall1 filter ?xs ?f)" => "(Filteri ?f (Num 0) ?xs)"),
        rw!("m-call1-6"; "(MCall1 find ?xs ?f)" => "(IndexQ (Filteri ?f (Num 0) ?xs) (Num 0))"),
        rw!("m-call1-7"; "(MCall1 concat ?xs ?ys)" => "(Append ?xs ?ys)"),
        rw!("m-call0-2"; "(MCall0 toReversed ?xs)" => "(Reverse ?xs)"),
        rw!("truthy-len"; "(Truthy (Len ?xs))" => "(Lt (Num 0) (Len ?xs))"),
        rw!("truthy-lt"; "(Truthy (Lt ?a ?b))" => "(Lt ?a ?b)"),
        rw!("truthy-le"; "(Truthy (Le ?a ?b))" => "(Le ?a ?b)"),
        rw!("truthy-eq-i"; "(Truthy (EqI ?a ?b))" => "(EqI ?a ?b)"),
        rw!("truthy-strict-eq"; "(Truthy (StrictEq ?a ?b))" => "(StrictEq ?a ?b)"),
        rw!("truthy-not"; "(Truthy (Not ?a))" => "(Not ?a)"),
        rw!("truthy-and"; "(Truthy (And ?a ?b))" => "(And ?a ?b)"),
        rw!("truthy-or"; "(Truthy (Or ?a ?b))" => "(Or ?a ?b)"),
        rw!("truthy-b"; "(Truthy (B ?b))" => "(B ?b)"),
        rw!("app-lam"; "(App (Lam ?v ?body) ?e)" => "(Let ?v ?e ?body)"),
        rw!("mul-num"; "(Mul (Num 0) ?a)" => "(Num 0)"),
        rw!("eq-i"; "(EqI ?a ?b)" => "(And (Le ?a ?b) (Le ?b ?a))"),
        rw!("not-lt"; "(Not (Lt ?a ?b))" => "(Le ?b ?a)"),
        rw!("not-le"; "(Not (Le ?a ?b))" => "(Lt ?b ?a)"),
        rw!("not-not"; "(Not (Not ?a))" => "?a"),
        rw!("and-b"; "(And (B true) ?a)" => "?a"),
        rw!("and-b-2"; "(And ?a (B true))" => "?a"),
        rw!("and-b-3"; "(And (B false) ?a)" => "(B false)"),
        rw!("and-b-4"; "(And ?a (B false))" => "(B false)"),
        rw!("and"; "(And ?a ?a)" => "?a"),
        rw!("or-b"; "(Or (B false) ?a)" => "?a"),
        rw!("or-b-2"; "(Or ?a (B false))" => "?a"),
        rw!("or-b-3"; "(Or (B true) ?a)" => "(B true)"),
        rw!("or-b-4"; "(Or ?a (B true))" => "(B true)"),
        rw!("if-b"; "(If (B true) ?a ?b)" => "?a"),
        rw!("if-b-2"; "(If (B false) ?a ?b)" => "?b"),
        rw!("if"; "(If ?c ?a ?a)" => "?a"),
        rw!("if-b-b"; "(If ?c (B true) (B false))" => "?c"),
        rw!("if-b-b-2"; "(If ?c (B false) (B true))" => "(Not ?c)"),
        rw!("if-not"; "(If (Not ?c) ?a ?b)" => "(If ?c ?b ?a)"),
        rw!("if-if"; "(If ?c (If ?c ?a ?b) ?d)" => "(If ?c ?a ?d)"),
        rw!("if-if-2"; "(If ?c ?a (If ?c ?b ?d))" => "(If ?c ?a ?d)"),
        rw!("strict-eq-num-undef"; "(StrictEq (Num ?a) (Undef))" => "(B false)"),
        rw!("strict-eq-b-undef"; "(StrictEq (B ?a) (Undef))" => "(B false)"),
        rw!("strict-eq-undef-undef"; "(StrictEq (Undef) (Undef))" => "(B true)"),
        rw!("strict-eq-at-undef"; "(StrictEq (At ?xs ?k) (Undef))" => "(B false)"),
        rw!("strict-eq-if"; "(StrictEq (If ?c ?a ?b) ?d)" => "(If ?c (StrictEq ?a ?d) (StrictEq ?b ?d))"),
        rw!("index-q"; "(IndexQ ?xs ?k)" => "(If (And (Le (Num 0) ?k) (Lt ?k (Len ?xs))) (At ?xs ?k) (Undef))" if expand_read("?xs", "?k")),
        rw!("len-nil"; "(Len (Nil))" => "(Num 0)"),
        rw!("len-cons"; "(Len (Cons ?h ?t))" => "(Add (Num 1) (Len ?t))"),
        rw!("len-append"; "(Len (Append ?a ?b))" => "(Add (Len ?a) (Len ?b))" if non_nil("?a") if non_nil("?b")),
        rw!("len-sublist"; "(Len (Sublist ?xs ?s ?e))" => "(Max (Sub ?e ?s) (Num 0))"),
        rw!("len-map"; "(Len (Map ?f ?xs))" => "(Len ?xs)"),
        rw!("len-reverse"; "(Len (Reverse ?xs))" => "(Len ?xs)"),
        rw!("append-nil"; "(Append (Nil) ?b)" => "?b"),
        rw!("append-nil-2"; "(Append ?a (Nil))" => "?a"),
        rw!("append-cons"; "(Append (Cons ?h ?t) ?b)" => "(Cons ?h (Append ?t ?b))"),
        rw!("append-if"; "(Append (If ?c ?a ?b) ?t)" => "(If ?c (Append ?a ?t) (Append ?b ?t))"),
        rw!("at-nil"; "(At (Nil) ?k)" => "(Oob)"),
        rw!("at-cons"; "(At (Cons ?h ?t) ?k)" => "(If (Lt (Num 0) ?k) (At ?t (Sub ?k (Num 1))) (If (EqI ?k (Num 0)) ?h (Oob)))"),
        rw!("at-append"; "(At (Append ?a ?b) ?k)" => "(If (Lt ?k (Num 0)) (Oob) (If (Lt ?k (Len ?a)) (At ?a ?k) (At ?b (Sub ?k (Len ?a)))))" if non_nil("?a") if non_nil("?b")),
        rw!("at-sublist"; "(At (Sublist ?xs ?s ?e) ?k)" => "(If (And (Le (Num 0) ?k) (Lt ?k (Sub ?e ?s))) (At ?xs (Add ?s ?k)) (Oob))" if known("?s") if known("?e")),
        rw!("at-map"; "(At (Map ?f ?xs) ?k)" => "(If (And (Le (Num 0) ?k) (Lt ?k (Len ?xs))) (App ?f (At ?xs ?k)) (Oob))"),
        rw!("at-reverse"; "(At (Reverse ?xs) ?k)" => "(If (And (Le (Num 0) ?k) (Lt ?k (Len ?xs))) (At ?xs (Sub (Sub (Len ?xs) (Num 1)) ?k)) (Oob))"),
        rw!("at-if"; "(At (If ?c ?a ?b) ?k)" => "(If ?c (At ?a ?k) (At ?b ?k))"),
        rw!("index-q-if"; "(IndexQ (If ?c ?a ?b) ?k)" => "(If ?c (IndexQ ?a ?k) (IndexQ ?b ?k))"),
        rw!("filteri-nil"; "(Filteri ?f ?k (Nil))" => "(Nil)" if not_index_predicate("?f")),
        rw!("filteri-cons"; "(Filteri ?f ?k (Cons ?h ?t))" => "(If (Truthy (App (App ?f ?h) ?k)) (Cons ?h (Filteri ?f (Add ?k (Num 1)) ?t)) (Filteri ?f (Add ?k (Num 1)) ?t))" if not_index_predicate("?f")),
        rw!("filteri-if"; "(Filteri ?f ?k (If ?c ?a ?b))" => "(If ?c (Filteri ?f ?k ?a) (Filteri ?f ?k ?b))" if not_index_predicate("?f")),
        rw!("foldl-nil"; "(Foldl ?f ?z (Nil))" => "?z"),
        rw!("foldl-cons"; "(Foldl ?f ?z (Cons ?h ?t))" => "(Foldl ?f (App (App ?f ?z) ?h) ?t)"),
        rw!("foldl-if"; "(Foldl ?f ?z (If ?c ?a ?b))" => "(If ?c (Foldl ?f ?z ?a) (Foldl ?f ?z ?b))"),
        rw!("maybe-undef"; "(Maybe ?z (Undef))" => "?z"),
        rw!("maybe-undef-2"; "(Maybe (Undef) ?m)" => "?m"),
        rw!("maybe-oob"; "(Maybe ?z (Oob))" => "(Oob)"),
        rw!("maybe-maybe"; "(Maybe ?z (Maybe ?z ?m))" => "(Maybe ?z ?m)"),
        rw!("maybe-at"; "(Maybe ?z (At ?xs ?k))" => "(At ?xs ?k)"),
        rw!("maybe-num"; "(Maybe ?z (Num ?n))" => "(Num ?n)"),
        rw!("not-true"; "(Not (B true))" => "(B false)"),
        rw!("not-false"; "(Not (B false))" => "(B true)"),
        rw!("eq-mirror-undef"; "(StrictEq Undef ?a)" => "(StrictEq ?a Undef)"),
        rw!("eq-mirror-if"; "(StrictEq ?a (If ?c ?b ?d))" => "(If ?c (StrictEq ?a ?b) (StrictEq ?a ?d))"),
        rw!("eq-bool-true"; "(StrictEq (B true) (B true))" => "(B true)"),
        rw!("eq-bool-false"; "(StrictEq (B false) (B false))" => "(B true)"),
        rw!("eq-bool-mixed"; "(StrictEq (B true) (B false))" => "(B false)"),
        rw!("eq-bool-mixed-mirror"; "(StrictEq (B false) (B true))" => "(B false)"),
        rw!("eq-integer"; "(StrictEq ?a ?b)" => "(EqI ?a ?b)" if integer("?a") if integer("?b")),
        rw!("maybe-int"; "(Maybe ?z ?a)" => "?a" if integer("?a")),
        rw!("normalize-add"; "(Add ?a ?b)" => { Normalize("Add") }),
        rw!("normalize-sub"; "(Sub ?a ?b)" => { Normalize("Sub") }),
        rw!("normalize-neg"; "(Neg ?a)" => { Normalize("Neg") }),
        rw!("normalize-lt"; "(Lt ?a ?b)" => { Compare(true) }),
        rw!("normalize-le"; "(Le ?a ?b)" => { Compare(false) }),
        rw!("relative-width"; "(Sub (Rel ?b ?n) (Rel ?a ?n))" => Width),
        rw!("sublist-width"; "(Sublist ?xs ?a ?b)" => SeedLength),
        rw!("short-fold"; "(Foldl ?f ?z ?xs)" => ShortFold),
        rw!("let-substitute"; "(Let ?v ?e ?body)" => Substitute),
        rw!("normalize-affine"; "?x" => NormalizeAffine),
        rw!("F4"; "(Foldl (Lam ?acc (Lam ?v ?body)) ?z ?xs)" => "(If (Lt (Num 0) (Len ?xs)) (Let ?v (At ?xs (Sub (Len ?xs) (Num 1))) ?body) ?z)" if different("?acc","?v") if independent("?acc","?body") if not_identity("?v","?body")),
        rw!("index-eq"; "(Filteri (Lam ?e (Lam ?idx (StrictEq (Var ?idx) ?j))) ?k ?xs)" => "(Select ?xs (Sub ?j ?k))" if different("?e","?idx") if independent("?e","?j") if independent("?idx","?j")),
        rw!("index-eq-mirror"; "(Filteri (Lam ?e (Lam ?idx (StrictEq ?j (Var ?idx)))) ?k ?xs)" => "(Select ?xs (Sub ?j ?k))" if different("?e","?idx") if independent("?e","?j") if independent("?idx","?j")),
        rw!("I1"; "(At ?xs ?k)" => SeedIndex),
    ];
    rules.push(rw!("M1"; "(If ?c (At ?xs ?k) ?z)" => MaybeFromRead));
    rules
}
