// Directed rewrite rules. The analysis in engine.rs carries bounds, booleans, strings,
// definedness, and opacity, and conditions consult those facts rather than node shapes.
// - Select is the zero-or-one-element list at an index, so projection stays relational
//   without distributing conditionals through every consumer.
// - === has explicit mirror rules; there is no general commutation or association.
// - Short-list structure is exposed only at its consumers. Rel and At(Sublist) stay semantic
//   primitives until concrete endpoints justify opening their definitions. The short-list
//   folds and the relational read lemmas (prefix-last, short-last) leave literal lists
//   alone, and no partial read is seeded at a known position of a literal: a literal Cons
//   or Nil belongs to at-cons, foldl-cons, filteri-cons, join-cons, and flat-cons.
// - Distribution never enters an If whose condition is decided: the class already holds the
//   live branch, and the dead one can unfold forever.
// - Comparison and negation rewrites stop once a class's boolean is known, and integer
//   equality on a live conditional is decided by distributing === into its branches only.
fn make_rules() -> Vec<Rule> {
    let mut rules = vec![
        rw!("reduce-cons"; "(MCall1 reduce (Cons ?h ?t) ?f)" => "(Foldl ?f ?h ?t)"),
        rw!("F4-identity"; "(Foldl (Lam ?acc (Lam ?v (Var ?v))) ?z ?xs)" => "(Maybe ?z (IndexQ ?xs (Sub (Len ?xs) (Num 1))))" if different("?acc","?v")),
        rw!("select-first"; "(IndexQ (Select ?xs ?j) (Num 0))" => "(IndexQ ?xs ?j)"),
        rw!("select-first-total"; "(At (Select ?xs ?j) (Num 0))" => "(At ?xs ?j)"),
        rw!("append-default"; "(IndexQ (Append ?xs (Cons ?z ?tail)) (Num 0))" => "(Maybe ?z (IndexQ ?xs (Num 0)))"),
        rw!("prefix-last"; "(IndexQ (Cons ?z ?xs) (Len ?xs))" => "(Maybe ?z (IndexQ ?xs (Sub (Len ?xs) (Num 1))))" if unknown_length("?xs")),
        rw!("sublist-tail"; "(Sublist (Cons ?h ?t) (Num 1) (Len (Cons ?h ?t)))" => "?t"),
        rw!("short-last"; "(IndexQ ?xs ?k)" => ShortRead),
        rw!("prop"; "(Prop ?xs length)" => "(Len ?xs)"),
        rw!("elem"; "(Elem ?xs ?k)" => "(IndexQ ?xs ?k)"),
        rw!("arr-cons"; "(ArrCons ?h ?t)" => "(Cons ?h ?t)"),
        rw!("arr-spread"; "(ArrSpread ?xs ?t)" => "(Append ?xs ?t)"),
        rw!("coalesce"; "(Coalesce ?a ?b)" => "(Maybe ?b ?a)"),
        rw!("default"; "(Default ?m ?d)" => "(Maybe ?d ?m)"),
        rw!("m-call2"; "(MCall2 slice ?xs ?a ?b)" => "(Sublist ?xs (Rel ?a (Len ?xs)) (Rel ?b (Len ?xs)))"),
        rw!("m-call1"; "(MCall1 slice ?xs ?a)" => "(Sublist ?xs (Rel ?a (Len ?xs)) (Len ?xs))"),
        rw!("m-call0"; "(MCall0 slice ?xs)" => "?xs"),
        rw!("rel"; "(Rel ?k ?n)" => "(If (Lt ?k (Num 0)) (Max (Add ?n ?k) (Num 0)) (Min ?k ?n))" if known("?k")),
        rw!("m-call1-2"; "(MCall1 at ?xs ?k)" => "(IndexQ ?xs (If (Lt ?k (Num 0)) (Add (Len ?xs) ?k) ?k))"),
        rw!("m-call2-2"; "(MCall2 reduce ?xs ?f ?z)" => "(Foldl ?f ?z ?xs)"),
        rw!("m-call1-3"; "(MCall1 reduce ?xs ?f)" => "(If (Lt (Num 0) (Len ?xs)) (Foldl ?f (At ?xs (Num 0)) (Sublist ?xs (Num 1) (Len ?xs))) (Throw))" if not_cons("?xs")),
        rw!("m-call1-4"; "(MCall1 map ?xs ?f)" => "(Map ?f (Num 0) ?xs)"),
        rw!("m-call1-5"; "(MCall1 filter ?xs ?f)" => "(Filteri ?f (Num 0) ?xs)"),
        rw!("m-call1-6"; "(MCall1 find ?xs ?f)" => "(IndexQ (Filteri ?f (Num 0) ?xs) (Num 0))"),
        rw!("m-call1-7"; "(MCall1 concat ?xs ?ys)" => "(Append ?xs ?ys)"),
        rw!("m-call0-2"; "(MCall0 toReversed ?xs)" => "(Reverse ?xs)"),
        rw!("m-call1-every"; "(MCall1 every ?xs ?f)" => "(Every ?f (Num 0) ?xs)"),
        rw!("m-call1-some"; "(MCall1 some ?xs ?f)" => "(Some ?f (Num 0) ?xs)"),
        rw!("short-every"; "(Every ?f ?k ?xs)" => { Walk::Every }),
        rw!("short-some"; "(Some ?f ?k ?xs)" => { Walk::Some }),
        rw!("short-count"; "(Len (Filteri ?f ?k ?xs))" => { Walk::Count } if not_literal("?xs")),
        rw!("m-call1-join"; "(MCall1 join ?xs ?s)" => "(Join ?s ?xs)"),
        rw!("m-call0-join"; "(MCall0 join ?xs)" => "(Join (Str utf16:002c) ?xs)"),
        rw!("join-nil"; "(Join ?s (Nil))" => "(Str utf16:)"),
        rw!("join-one"; "(Join ?s (Cons ?h (Nil)))" => "(JoinText ?h)"),
        rw!("join-cons"; "(Join ?s (Cons ?h (Cons ?g ?t)))" => "(Concat (Concat (JoinText ?h) ?s) (Join ?s (Cons ?g ?t)))"),
        rw!("join-text"; "(JoinText ?x)" => "?x" if string("?x")),
        rw!("short-join"; "(Join ?s ?xs)" => { Walk::Join } if not_literal("?xs")),
        // flat spreads each element one level: a list element is spread, any other is kept.
        rw!("m-call0-flat"; "(MCall0 flat ?xs)" => "(Flat ?xs)"),
        rw!("m-call1-flat-map"; "(MCall1 flatMap ?xs ?f)" => "(Flat (Map ?f (Num 0) ?xs))"),
        rw!("flat-nil"; "(Flat (Nil))" => "(Nil)"),
        rw!("flat-cons"; "(Flat (Cons ?h ?t))" => "(Append (Spread ?h) (Flat ?t))"),
        rw!("spread-list"; "(Spread ?x)" => "?x" if list("?x")),
        rw!("spread-scalar"; "(Spread ?x)" => "(Cons ?x (Nil))" if scalar("?x")),
        rw!("short-flat"; "(Flat ?xs)" => { Walk::Flat } if not_literal("?xs")),
        rw!("truthy-len"; "(Truthy (Len ?xs))" => "(Lt (Num 0) (Len ?xs))"),
        rw!("truthy-lt"; "(Truthy (Lt ?a ?b))" => "(Lt ?a ?b)"),
        rw!("truthy-le"; "(Truthy (Le ?a ?b))" => "(Le ?a ?b)"),
        rw!("truthy-eq-i"; "(Truthy (EqI ?a ?b))" => "(EqI ?a ?b)"),
        rw!("truthy-strict-eq"; "(Truthy (StrictEq ?a ?b))" => "(StrictEq ?a ?b)"),
        rw!("truthy-not"; "(Truthy (Not ?a))" => "(Not ?a)"),
        rw!("truthy-and"; "(Truthy (And ?a ?b))" => "(And ?a ?b)"),
        rw!("truthy-or"; "(Truthy (Or ?a ?b))" => "(Or ?a ?b)"),
        rw!("truthy-b"; "(Truthy (B ?b))" => "(B ?b)"),
        rw!("app-lam"; "(App (Lam ?v ?body) ?e)" => "(Let ?v ?e ?body)"),
        rw!("call2"; "(Call2 ?f ?a ?b)" => Call2),
        rw!("mul-num"; "(Mul (Num 0) ?a)" => "(Num 0)"),
        rw!("eq-i"; "(EqI ?a ?b)" => "(And (Le ?a ?b) (Le ?b ?a))" if undecided()),
        rw!("not-lt"; "(Not (Lt ?a ?b))" => "(Le ?b ?a)" if undecided()),
        rw!("not-le"; "(Not (Le ?a ?b))" => "(Lt ?b ?a)" if undecided()),
        rw!("not-not"; "(Not (Not ?a))" => "?a"),
        rw!("not-if"; "(Not (If ?c ?a ?b))" => "(If ?c (Not ?a) (Not ?b))" if undecided() if live("?c") if presence("?c")),
        rw!("or-if"; "(Or ?a ?b)" => "(If ?a (B true) ?b)" if live("?a") if live("?b")),
        rw!("and-if"; "(And ?a ?b)" => "(If ?a ?b (B false))" if live("?a") if live("?b")),
        rw!("and-b"; "(And (B true) ?a)" => "?a"),
        rw!("and-b-2"; "(And ?a (B true))" => "?a"),
        rw!("and-b-3"; "(And (B false) ?a)" => "(B false)"),
        rw!("and-b-4"; "(And ?a (B false))" => "(B false)"),
        rw!("and"; "(And ?a ?a)" => "?a"),
        rw!("or-b"; "(Or (B false) ?a)" => "?a"),
        rw!("or-b-2"; "(Or ?a (B false))" => "?a"),
        rw!("or-b-3"; "(Or (B true) ?a)" => "(B true)"),
        rw!("or-b-4"; "(Or ?a (B true))" => "(B true)"),
        rw!("if-b"; "(If (B true) ?a ?b)" => "?a"),
        rw!("if-b-2"; "(If (B false) ?a ?b)" => "?b"),
        rw!("if"; "(If ?c ?a ?a)" => "?a"),
        rw!("if-b-b"; "(If ?c (B true) (B false))" => "?c"),
        rw!("if-b-b-2"; "(If ?c (B false) (B true))" => "(Not ?c)"),
        rw!("if-not"; "(If (Not ?c) ?a ?b)" => "(If ?c ?b ?a)"),
        rw!("if-if"; "(If ?c (If ?c ?a ?b) ?d)" => "(If ?c ?a ?d)"),
        rw!("if-if-2"; "(If ?c ?a (If ?c ?b ?d))" => "(If ?c ?a ?d)"),
        rw!("strict-eq-undef-undef"; "(StrictEq (Undef) (Undef))" => "(B true)"),
        rw!("strict-eq-defined-undef"; "(StrictEq ?a Undef)" => "(B false)" if defined("?a")),
        rw!("strict-eq-if"; "(StrictEq (If ?c ?a ?b) ?d)" => "(If ?c (StrictEq ?a ?d) (StrictEq ?b ?d))" if live("?c")),
        rw!("index-q"; "(IndexQ ?xs ?k)" => "(If (And (Le (Num 0) ?k) (Lt ?k (Len ?xs))) (At ?xs ?k) (Undef))" if expand_read("?xs", "?k")),
        rw!("len-nil"; "(Len (Nil))" => "(Num 0)"),
        rw!("len-cons"; "(Len (Cons ?h ?t))" => "(Add (Num 1) (Len ?t))"),
        rw!("len-append"; "(Len (Append ?a ?b))" => "(Add (Len ?a) (Len ?b))" if non_nil("?a") if non_nil("?b")),
        rw!("len-sublist"; "(Len (Sublist ?xs ?s ?e))" => "(Max (Sub ?e ?s) (Num 0))"),
        rw!("len-map"; "(Len (Map ?f ?k ?xs))" => "(Len ?xs)"),
        // Map f k xs maps f over xs, passing indexes counted from k, like Filteri.
        rw!("map-nil"; "(Map ?f ?k (Nil))" => "(Nil)"),
        rw!("map-cons"; "(Map ?f ?k (Cons ?h ?t))" => "(Cons (Call2 ?f ?h ?k) (Map ?f (Add ?k (Num 1)) ?t))"),
        rw!("len-reverse"; "(Len (Reverse ?xs))" => "(Len ?xs)"),
        rw!("append-nil"; "(Append (Nil) ?b)" => "?b"),
        rw!("append-nil-2"; "(Append ?a (Nil))" => "?a"),
        rw!("append-cons"; "(Append (Cons ?h ?t) ?b)" => "(Cons ?h (Append ?t ?b))"),
        rw!("append-if"; "(Append (If ?c ?a ?b) ?t)" => "(If ?c (Append ?a ?t) (Append ?b ?t))" if live("?c")),
        rw!("at-nil"; "(At (Nil) ?k)" => "(Oob)"),
        rw!("at-cons"; "(At (Cons ?h ?t) ?k)" => AtCons),
        rw!("at-append"; "(At (Append ?h ?t) ?k)" => AtAppend if non_nil("?h") if non_nil("?t")),
        rw!("at-sublist"; "(At (Sublist ?xs ?s ?e) ?k)" => "(If (And (Le (Num 0) ?k) (Lt ?k (Sub ?e ?s))) (At ?xs (Add ?s ?k)) (Oob))" if known("?s") if known("?e")),
        rw!("at-map"; "(At (Map ?f ?j ?xs) ?k)" => "(If (And (Le (Num 0) ?k) (Lt ?k (Len ?xs))) (Call2 ?f (At ?xs ?k) (Add ?j ?k)) (Oob))"),
        rw!("at-reverse"; "(At (Reverse ?xs) ?k)" => "(If (And (Le (Num 0) ?k) (Lt ?k (Len ?xs))) (At ?xs (Sub (Sub (Len ?xs) (Num 1)) ?k)) (Oob))"),
        rw!("at-if"; "(At (If ?c ?a ?b) ?k)" => "(If ?c (At ?a ?k) (At ?b ?k))" if live("?c")),
        rw!("index-q-if"; "(IndexQ (If ?c ?a ?b) ?k)" => "(If ?c (IndexQ ?a ?k) (IndexQ ?b ?k))" if live("?c")),
        rw!("filteri-nil"; "(Filteri ?f ?k (Nil))" => "(Nil)" if not_index_predicate("?f")),
        rw!("filteri-cons"; "(Filteri ?f ?k (Cons ?h ?t))" => "(If (Truthy (Call2 ?f ?h ?k)) (Cons ?h (Filteri ?f (Add ?k (Num 1)) ?t)) (Filteri ?f (Add ?k (Num 1)) ?t))" if not_index_predicate("?f")),
        rw!("filteri-if"; "(Filteri ?f ?k (If ?c ?a ?b))" => "(If ?c (Filteri ?f ?k ?a) (Filteri ?f ?k ?b))" if not_index_predicate("?f") if live("?c")),
        rw!("foldl-nil"; "(Foldl ?f ?z (Nil))" => "?z"),
        rw!("foldl-cons"; "(Foldl ?f ?z (Cons ?h ?t))" => "(Foldl ?f (Call2 ?f ?z ?h) ?t)"),
        rw!("foldl-if"; "(Foldl ?f ?z (If ?c ?a ?b))" => "(If ?c (Foldl ?f ?z ?a) (Foldl ?f ?z ?b))" if live("?c")),
        rw!("maybe-undef"; "(Maybe ?z (Undef))" => "?z"),
        rw!("maybe-undef-2"; "(Maybe (Undef) ?m)" => "?m"),
        rw!("maybe-oob"; "(Maybe ?z (Oob))" => "(Oob)"),
        rw!("maybe-maybe"; "(Maybe ?z (Maybe ?z ?m))" => "(Maybe ?z ?m)"),
        rw!("maybe-defined"; "(Maybe ?z ?m)" => "?m" if defined("?m")),
        rw!("not-true"; "(Not (B true))" => "(B false)"),
        rw!("not-false"; "(Not (B false))" => "(B true)"),
        rw!("eq-mirror-undef"; "(StrictEq Undef ?a)" => "(StrictEq ?a Undef)"),
        rw!("eq-mirror-if"; "(StrictEq ?a (If ?c ?b ?d))" => "(If ?c (StrictEq ?a ?b) (StrictEq ?a ?d))" if live("?c")),
        rw!("eq-bool-true"; "(StrictEq (B true) (B true))" => "(B true)"),
        rw!("eq-bool-false"; "(StrictEq (B false) (B false))" => "(B true)"),
        rw!("eq-bool-mixed"; "(StrictEq (B true) (B false))" => "(B false)"),
        rw!("eq-bool-mixed-mirror"; "(StrictEq (B false) (B true))" => "(B false)"),
        rw!("eq-integer"; "(StrictEq ?a ?b)" => "(EqI ?a ?b)" if integer("?a") if integer("?b") if undecided() if unbranched("?a") if unbranched("?b")),
        rw!("normalize-add"; "(Add ?a ?b)" => { Normalize("Add") }),
        rw!("normalize-sub"; "(Sub ?a ?b)" => { Normalize("Sub") }),
        rw!("normalize-neg"; "(Neg ?a)" => { Normalize("Neg") }),
        rw!("normalize-lt"; "(Lt ?a ?b)" => { Compare(true) } if undecided()),
        rw!("normalize-le"; "(Le ?a ?b)" => { Compare(false) } if undecided()),
        rw!("relative-width"; "(Sub (Rel ?b ?n) (Rel ?a ?n))" => Width),
        rw!("sublist-width"; "(Sublist ?xs ?a ?b)" => SeedLength),
        rw!("short-fold"; "(Foldl ?f ?z ?xs)" => ShortFold if not_literal("?xs")),
        rw!("let-substitute"; "(Let ?v ?e ?body)" => Substitute),
        rw!("normalize-affine"; "?x" => NormalizeAffine),
        rw!("F4"; "(Foldl (Lam ?acc (Lam ?v ?body)) ?z ?xs)" => "(If (Lt (Num 0) (Len ?xs)) (Let ?v (At ?xs (Sub (Len ?xs) (Num 1))) ?body) ?z)" if different("?acc","?v") if independent("?acc","?body") if not_identity("?v","?body") if not_function("?body")),
        rw!("index-eq"; "(Filteri (Lam ?e (Lam ?idx (StrictEq (Var ?idx) ?j))) ?k ?xs)" => "(Select ?xs (Sub ?j ?k))" if different("?e","?idx") if independent("?e","?j") if independent("?idx","?j")),
        rw!("index-eq-mirror"; "(Filteri (Lam ?e (Lam ?idx (StrictEq ?j (Var ?idx)))) ?k ?xs)" => "(Select ?xs (Sub ?j ?k))" if different("?e","?idx") if independent("?e","?j") if independent("?idx","?j")),
        rw!("I1"; "(At ?xs ?k)" => SeedIndex),
    ];
    rules.push(rw!("M1"; "(If ?c ?t ?z)" => MaybeFromRead));
    rules
}
